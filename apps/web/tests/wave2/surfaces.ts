export function assertSurfaceManifest(rows: readonly Surface[] = SURFACES): void {
  const expected = [
    ['S', 32],
    ['L', 22],
    ['A', 13],
  ] as const
  const ids = rows.map((row) => row.id)
  guard(ids.length === 67 && new Set(ids).size === 67, 'SURFACES_COMPLETENESS')
  for (const [prefix, count] of expected)
    for (let i = 1; i <= count; i++) {
      const row = rows.find((row) => row.id === `${prefix}${String(i).padStart(2, '0')}`)
      guard(
        row && row.origin === ({ S: 'web', L: 'landing', A: 'auth' } as const)[prefix],
        'SURFACES_ORIGIN'
      )
      guard(row.roles.length && row.gate && row.source, 'SURFACES_EVIDENCE')
      guard(
        ['Source verified', 'Operator pending', 'Commercial-gated', 'Deferred'].includes(
          row.classification
        ) && ['stable', 'settled-destination', 'email'].includes(row.visual),
        'SURFACES_CLASSIFICATION'
      )
      guard(
        row.roles.every((role) =>
          ['anonymous', 'org_owner', 'org_admin', 'org_member', 'org_billing'].includes(role)
        ),
        'SURFACES_ROLE'
      )
    }
  guard(
    rows.filter((row) => row.origin === 'web').every((row) => row.oracles.length > 0),
    'SURFACES_ORACLES'
  )
  guard(
    rows.filter((row) => row.origin === 'auth').every((row) => row.routePattern === null),
    'SURFACES_OWNED_TRANSACTION'
  )
}

export function fixturePath(pattern: string, values: Readonly<Record<string, string>>): string {
  return pattern.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = values[key]
    guard(typeof value === 'string' && value.length > 0, 'SURFACES_FIXTURE_REQUIRED')
    return encodeURIComponent(value)
  })
}
