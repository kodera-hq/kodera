"""Render `yjs_collab/title-key-table.mjs`, the collaboration service's copy of `titles.key`.

Run `python -m apps.docs.title_key_table` from `apps/server` after a Python Unicode upgrade;
`tests/workspace_documents/test_title_keys.py` fails while the checked-in table differs.
"""

import json
import sys
import unicodedata
from pathlib import Path

TABLE = Path(__file__).resolve().parents[2] / "yjs_collab" / "title-key-table.mjs"


def folds() -> dict[int, str]:
    return {
        point: chr(point).casefold()
        for point in range(sys.maxunicode + 1)
        if not 0xD800 <= point <= 0xDFFF and chr(point).casefold() != chr(point)
    }


def render() -> str:
    lines = [
        "/** Unicode full case folding for document title keys (`apps/docs/titles.py`).",
        " * Generated by `python -m apps.docs.title_key_table` in `apps/server`; do not edit. */",
        f"export const UNICODE_VERSION = {json.dumps(unicodedata.unidata_version)}",
        "export const FOLDS = new Map([",
        *(f"  [0x{point:04X}, {json.dumps(value)}]," for point, value in folds().items()),
        "])",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TABLE.write_text(render(), encoding="ascii")
