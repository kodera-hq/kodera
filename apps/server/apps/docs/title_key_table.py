"""Render `yjs_collab/title-key-table.mjs`, the collaboration service's copy of `titles.key`.

Run `python -m apps.docs.title_key_table` from `apps/server` after a Python Unicode upgrade;
`tests/workspace_documents/test_title_keys.py` fails while the checked-in table differs.
"""

import json
import sys
import unicodedata
from pathlib import Path

from . import titles

TABLE = Path(__file__).resolve().parents[2] / "yjs_collab" / "title-key-table.mjs"
S_BASE = 0xAC00
S_COUNT = 19 * 21 * 28
PAIR_STRIDE = 0x200000


def folds() -> dict[int, str]:
    return {
        point: chr(point).casefold()
        for point in range(sys.maxunicode + 1)
        if not 0xD800 <= point <= 0xDFFF and chr(point).casefold() != chr(point)
    }


def decompositions() -> dict[int, list[int]]:
    result: dict[int, list[int]] = {}
    for point in range(sys.maxunicode + 1):
        if 0xD800 <= point <= 0xDFFF or S_BASE <= point < S_BASE + S_COUNT:
            continue
        character = chr(point)
        decomposed = unicodedata.normalize("NFD", character)
        if decomposed != character:
            result[point] = [ord(item) for item in decomposed]
    return result


def combining_classes() -> dict[int, int]:
    result: dict[int, int] = {}
    for point in range(sys.maxunicode + 1):
        if 0xD800 <= point <= 0xDFFF:
            continue
        ccc = unicodedata.combining(chr(point))
        if ccc:
            result[point] = ccc
    return result


def compositions() -> dict[tuple[int, int], int]:
    result: dict[tuple[int, int], int] = {}
    for point in range(sys.maxunicode + 1):
        if 0xD800 <= point <= 0xDFFF or S_BASE <= point < S_BASE + S_COUNT:
            continue
        raw = unicodedata.decomposition(chr(point))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(part, 16) for part in raw.split()]
        if len(parts) == 2:
            left, right = parts
            character = chr(point)
            if unicodedata.normalize("NFC", chr(left) + chr(right)) == character:
                result[(left, right)] = point
    return result


def _hex_list(points: list[int]) -> str:
    return "[" + ", ".join(f"0x{point:04X}" for point in points) + "]"


def render() -> str:
    lines = [
        "/** Unicode NFC and full case folding for document title keys (`apps/docs/titles.py`).",
        " * Generated by `python -m apps.docs.title_key_table` in `apps/server`; do not edit. */",
        f"export const UNICODE_VERSION = {json.dumps(unicodedata.unidata_version)}",
        f"export const KEY_EXPANSION = {titles.KEY_EXPANSION}",
        f"export const MAX_KEY_LENGTH = {titles.MAX_KEY_LENGTH}",
        f"export const PAIR_STRIDE = 0x{PAIR_STRIDE:X}",
        "export const DECOMPOSITIONS = new Map([",
        *(f"  [0x{point:04X}, {_hex_list(parts)}]," for point, parts in decompositions().items()),
        "])",
        "export const COMBINING_CLASSES = new Map([",
        *(f"  [0x{point:04X}, {ccc}]," for point, ccc in combining_classes().items()),
        "])",
        "export const COMPOSITIONS = new Map([",
        *(
            f"  [0x{left * PAIR_STRIDE + right:X}, 0x{composite:04X}],"
            for (left, right), composite in compositions().items()
        ),
        "])",
        "export const FOLDS = new Map([",
        *(f"  [0x{point:04X}, {json.dumps(value)}]," for point, value in folds().items()),
        "])",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TABLE.write_text(render(), encoding="ascii")
