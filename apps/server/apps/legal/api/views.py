"""listLegalDocuments, generateDpa and getDpa (contracts/core-api.openapi.yaml, tags Catalog, DPA).

The documents in force are public. A DPA is the organisation's: it is generated by its owner and
read by the roles AUTHZ.md §5 gives `read own` on the DpaAcceptance row; a staff token is refused
until the staff lane is built. generateDpa authorises the caller against current state, then hands
the request to the replay store, which runs the step once per key.
"""

import json
import logging
import re
from typing import Any
from uuid import UUID

from django.conf import settings
from django.core.exceptions import TooManyFieldsSent
from django.http import HttpRequest, HttpResponse, QueryDict

from apps.legal import services
from core.api import lanes, problems
from core.api.idempotency import MALFORMED, PROBLEM_TYPE, StoredResponse, problem, respond_once
from core.api.scopes import declares
from core.db.ids import new_uuid7
from services.identity.access_tokens import MAX_TOKEN, TokenVerificationError
from services.identity.trusted_issuers import verify_configured_token

from .permissions import GENERATE_DPA, GET_DPA, GET_LEGAL_DOCUMENT_TEXT, LIST_LEGAL_DOCUMENTS

REQUEST_ID = re.compile(r"[A-Za-z0-9_-]{8,64}\Z")
PROBLEM_BASE = "https://kodera.io/problems/"
PROBLEMS = {
    400: ("malformed-request", "Malformed request"),
    401: ("unauthenticated", "Authentication required"),
    403: ("forbidden", "Access refused"),
    404: ("not-found", "Not found"),
    405: ("method-not-allowed", "Method not allowed"),
    422: ("validation-error", "Validation error"),
    500: ("internal-error", "Internal error"),
}
LOG = logging.getLogger(__name__)
READERS = frozenset({"org_owner", "org_admin", "org_billing"})
OWNER = frozenset({"org_owner"})
LIMIT = re.compile(r"[1-9][0-9]{0,2}\Z")


def _problem(
    status: int, request_id: str, *, allow: str = "GET", **extension: object
) -> HttpResponse:
    kind, title = PROBLEMS[status]
    body: dict[str, object] = {
        "type": PROBLEM_BASE + kind,
        "title": title,
        "status": status,
        "request_id": request_id,
        **extension,
    }
    if status == 405:
        body["allowed"] = [allow]
    response = HttpResponse(
        json.dumps(body), status=status, content_type="application/problem+json"
    )
    if status == 401:
        response["WWW-Authenticate"] = "Bearer"
    if status == 405:
        response["Allow"] = allow
    return response


def _request_id(request: HttpRequest) -> str:
    supplied = request.headers.get("X-Request-Id", "")
    return supplied if REQUEST_ID.fullmatch(supplied) else str(new_uuid7())


def _bearer(request: HttpRequest) -> str:
    authorization = request.headers.get("Authorization", "")
    if len(authorization) > MAX_TOKEN + 7:
        raise TokenVerificationError()
    parts = authorization.split(" ")
    if len(parts) != 2 or parts[0].lower() != "bearer" or not parts[1]:
        raise TokenVerificationError()
    return parts[1]


def _finish(response: HttpResponse, request_id: str) -> HttpResponse:
    response["Cache-Control"] = "no-store"
    response["X-Request-Id"] = request_id
    return response


class _StaffRefusedError(Exception):
    """A staff token: no staff lane on these operations yet (`403`)."""

    def __init__(self, verified: Any) -> None:
        super().__init__("staff")
        self.verified = verified


def _tenant(request: HttpRequest) -> Any:
    verified, lane = verify_configured_token(_bearer(request), trusted=settings.KODERA_AUTH_TRUST)
    verified, lane = lanes.admit(verified, lane)
    if lane == "staff":
        raise _StaffRefusedError(verified)
    return verified


def _refused(
    refused: Exception, verified: Any, organisation_id: UUID, scope: str, request_id: str
) -> HttpResponse:
    """The `403`, its `authz.denied` written first (AUTHZ.md §9); a `500` if it cannot be."""
    try:
        services.record_denial(
            verified=refused.verified if isinstance(refused, _StaffRefusedError) else verified,
            refused=refused if isinstance(refused, services.ForbiddenError) else None,
            organisation_id=organisation_id,
            scope=scope,
            request_id=request_id,
        )
    except Exception as failure:
        LOG.error("denial not recorded: %s request_id=%s", type(failure).__name__, request_id)
        return _problem(500, request_id)
    return _problem(403, request_id)


@declares(LIST_LEGAL_DOCUMENTS)
def legal_documents(request: HttpRequest) -> HttpResponse:
    request_id = _request_id(request)
    if request.method != "GET":
        return _finish(_problem(405, request_id), request_id)
    try:
        query = QueryDict(request.META.get("QUERY_STRING", ""))
    except TooManyFieldsSent:
        return _finish(_problem(400, request_id), request_id)
    allowed = {"cursor", "limit", "pack_code", "locale"}
    if any(
        key not in allowed or len(values) != 1 or not values[0] for key, values in query.lists()
    ):
        return _finish(_problem(400, request_id), request_id)
    limit = query.get("limit", "50")
    locale = query.get("locale")
    pack_code = query.get("pack_code")
    # Every document in force fits one page: no cursor is ever issued, so none is accepted.
    if not LIMIT.match(limit) or int(limit) > 200 or "cursor" in query:
        return _finish(_problem(400, request_id), request_id)
    if locale is not None and locale not in ("fr", "en"):
        return _finish(_problem(400, request_id), request_id)
    if pack_code is not None and (len(pack_code) > 64 or not pack_code.isascii()):
        return _finish(_problem(400, request_id), request_id)
    try:
        documents = services.documents_in_force(pack_code=pack_code, locale=locale)
    except Exception as failure:
        LOG.error("listLegalDocuments failed: %s request_id=%s", type(failure).__name__, request_id)
        return _finish(_problem(500, request_id), request_id)
    page = documents[: int(limit)]
    body = {
        "data": [services.document_representation(document) for document in page],
        "next_cursor": None,
        "has_more": False,
    }
    return _finish(HttpResponse(json.dumps(body), content_type="application/json"), request_id)


VERSION = re.compile(r"[0-9A-Za-z.-]{1,20}\Z")
# A published text never changes behind its version: a year of caching is safe.
IMMUTABLE = "public, max-age=31536000, immutable"


@declares(GET_LEGAL_DOCUMENT_TEXT)
def legal_document_text(request: HttpRequest, code: str, version: str, locale: str) -> HttpResponse:
    """The exact text a customer accepted, at its permanent URL: public, never edited."""
    request_id = _request_id(request)
    if request.method != "GET":
        return _finish(_problem(405, request_id), request_id)
    # A path outside the contract's parameter schemas is malformed and never reaches the
    # database; a well-formed key with no published text is not found.
    if code not in services.CODES or locale not in services.LOCALES or not VERSION.match(version):
        return _finish(_problem(400, request_id), request_id)
    try:
        document = services.published_text(code=code, version=version, locale=locale)
    except Exception as failure:
        LOG.error(
            "getLegalDocumentText failed: %s request_id=%s", type(failure).__name__, request_id
        )
        return _finish(_problem(500, request_id), request_id)
    if document is None or document.text is None:
        return _finish(_problem(404, request_id), request_id)
    # Plain text, so a browser shows it rather than downloads it: the Markdown is readable as is.
    response = HttpResponse(document.text.encode("utf-8"), content_type="text/plain; charset=utf-8")
    response["Cache-Control"] = IMMUTABLE
    response["ETag"] = f'"{document.sha256}"'
    response["X-Content-Type-Options"] = "nosniff"
    response["X-Request-Id"] = request_id
    return response


def _generate_step(
    request: HttpRequest, organisation_id: UUID, verified: Any, request_id: str
) -> StoredResponse:
    if request.content_type != "application/json":
        return problem(MALFORMED, request_id)
    try:
        payload = json.loads(request.body)
    except ValueError:
        return problem(MALFORMED, request_id)
    if not isinstance(payload, dict):
        return problem(MALFORMED, request_id)
    errors = [
        {"pointer": f"/{name}", "code": "unknown_member"}
        for name in sorted(set(payload) - {"pack_code", "tenant_id", "locale"})
    ]
    pack_code = payload.get("pack_code")
    if not isinstance(pack_code, str) or not 1 <= len(pack_code) <= 64:
        errors.append({"pointer": "/pack_code", "code": "required"})
        pack_code = ""
    locale = payload.get("locale", "fr")
    if locale not in ("fr", "en"):
        errors.append({"pointer": "/locale", "code": "type"})
    tenant_id = payload.get("tenant_id")
    if tenant_id is not None:
        # A DPA for an existing tenant arrives with tenant regeneration, not with the first order.
        errors.append({"pointer": "/tenant_id", "code": "not_supported"})
    if errors:
        body = {
            "type": PROBLEM_BASE + "validation-error",
            "title": "Validation error",
            "status": 422,
            "request_id": request_id,
            "errors": errors,
        }
        return StoredResponse(status=422, body=json.dumps(body).encode(), content_type=PROBLEM_TYPE)
    try:
        dpa, _ = services.generate_dpa(
            verified=verified,
            organisation_id=organisation_id,
            pack_code=pack_code,
            locale=locale,
            tenant_id=None,
        )
    except services.DpaNotFoundError:
        body = {
            "type": PROBLEM_BASE + "not-found",
            "title": "Not found",
            "status": 404,
            "request_id": request_id,
        }
        return StoredResponse(status=404, body=json.dumps(body).encode(), content_type=PROBLEM_TYPE)
    return StoredResponse(
        status=201,
        body=json.dumps(services.dpa_representation(dpa)).encode(),
        content_type="application/json",
        location=f"/api/v1/organisations/{organisation_id}/dpa/{dpa.id}",
    )


@declares(GENERATE_DPA)
def dpa(request: HttpRequest, organisation_id: UUID) -> HttpResponse:
    request_id = _request_id(request)
    verified = None
    try:
        if request.method != "POST":
            return _finish(_problem(405, request_id, allow="POST"), request_id)
        verified = _tenant(request)
        services.authorise(
            verified=verified,
            organisation_id=organisation_id,
            roles=OWNER,
            scope="dpa_acceptance:create",
        )
        response = respond_once(
            request,
            issuer=verified.issuer,
            subject=verified.subject,
            request_id=request_id,
            handler=lambda: _generate_step(request, organisation_id, verified, request_id),
        )
    except TokenVerificationError:
        response = _problem(401, request_id)
    except services.CallerUnknownError:
        response = problems.identity_unknown(request_id, GENERATE_DPA.operation_id)
    except (services.ForbiddenError, _StaffRefusedError) as refused:
        response = _refused(refused, verified, organisation_id, "dpa_acceptance:create", request_id)
    except services.NotFoundError:
        response = _problem(404, request_id)
    except Exception as failure:
        LOG.error("generateDpa failed: %s request_id=%s", type(failure).__name__, request_id)
        response = _problem(500, request_id)
    return _finish(response, request_id)


@declares(GET_DPA)
def dpa_detail(request: HttpRequest, organisation_id: UUID, dpa_id: UUID) -> HttpResponse:
    request_id = _request_id(request)
    verified = None
    try:
        if request.method != "GET":
            return _finish(_problem(405, request_id), request_id)
        verified = _tenant(request)
        found = services.read_dpa(verified=verified, organisation_id=organisation_id, dpa_id=dpa_id)
        response = HttpResponse(
            json.dumps(services.dpa_representation(found)), content_type="application/json"
        )
    except TokenVerificationError:
        response = _problem(401, request_id)
    except services.CallerUnknownError:
        response = problems.identity_unknown(request_id, GET_DPA.operation_id)
    except (services.ForbiddenError, _StaffRefusedError) as refused:
        response = _refused(refused, verified, organisation_id, "dpa_acceptance:read", request_id)
    except (services.NotFoundError, services.DpaNotFoundError):
        response = _problem(404, request_id)
    except Exception as failure:
        LOG.error("getDpa failed: %s request_id=%s", type(failure).__name__, request_id)
        response = _problem(500, request_id)
    return _finish(response, request_id)
