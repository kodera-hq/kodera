"""Prove inventory refusals using bounded tests in disposable source copies."""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MUTATIONS = [
    (
        "missing-population",
        [
            (
                "if not isinstance(rows, list) or len(rows) != len(REQUIRED):",
                "if not isinstance(rows, list):",
            ),
            ("if set(found) != set(REQUIRED):", "if False:"),
            (
                "selected = [args.case] if args.case else list(REQUIRED)",
                "selected = [args.case] if args.case else list(rows)",
            ),
        ],
        "test_invalid_manifest_cannot_admit_or_inject_results[missing]",
        "invalid manifests must be blocked before scenario reporting",
        "test_full_inventory_is_explicitly_non_passing",
    ),
    (
        "result-injection",
        [
            ('set(row) != {"id", "description"}', 'not {"id", "description"}.issubset(row)'),
        ],
        "test_invalid_manifest_cannot_admit_or_inject_results[result]",
        "invalid manifests must be blocked before scenario reporting",
        "test_full_inventory_is_explicitly_non_passing",
    ),
    (
        "false-success",
        [("        return 1\n", "        return 0\n")],
        "test_full_inventory_is_explicitly_non_passing",
        "absent product behavior must never return success",
        "test_unknown_case_is_blocked_without_echoing_input",
    ),
    (
        "content-insensitive-fingerprint",
        [("capture(chunk)", 'capture(b"content")')],
        "test_fingerprint_observes_content_not_only_status",
        "source fingerprint must change when file contents change",
        "test_full_inventory_is_explicitly_non_passing",
    ),
]


def main() -> None:
    outcomes = []
    environment = {
        key: os.environ[key]
        for key in ("PATH", "HOME", "TMPDIR", "LANG", "LC_ALL")
        if key in os.environ
    }
    with tempfile.TemporaryDirectory(prefix="first-slice-mutations-") as temporary:
        for name, changes, case, reason, control in MUTATIONS:
            root = Path(temporary) / name
            (root / "dev").mkdir(parents=True)
            (root / "tests").mkdir()
            for relative in [
                "Makefile",
                "dev/accept_first_slice.py",
                "dev/first_slice_manifest.json",
                "tests/test_first_slice_inventory.py",
            ]:
                shutil.copyfile(ROOT / relative, root / relative)
            path = root / "dev/accept_first_slice.py"
            source = path.read_text()
            for old, new in changes:
                if source.count(old) != 1:
                    raise RuntimeError("Mutation anchor is not unique: " + name)
                source = source.replace(old, new)
            path.write_text(source)
            (root / "pytest.ini").write_text("[pytest]\n")
            result = subprocess.run(  # noqa: S603 - fixed tests and interpreter, no caller commands
                [
                    sys.executable,
                    "-m",
                    "pytest",
                    "-c",
                    "pytest.ini",
                    "-p",
                    "no:django",
                    "--randomly-seed=1",
                    "--junitxml=result.xml",
                    f"tests/test_first_slice_inventory.py::{case}",
                    f"tests/test_first_slice_inventory.py::{control}",
                ],
                cwd=root,
                env=environment,
                capture_output=True,
                text=True,
                timeout=30,
            )
            # XML is generated by this exact local pytest process, not external input.
            report = ET.parse(root / "result.xml")  # noqa: S314
            cases = {entry.attrib["name"]: entry for entry in report.findall(".//testcase")}
            failure = cases[case].find("failure")
            caught = (
                result.returncode == 1
                and failure is not None
                and reason in failure.attrib.get("message", "")
            )
            intact = all(
                cases[control].find(kind) is None for kind in ["failure", "error", "skipped"]
            )
            outcomes.append(
                {
                    "mutation": name,
                    "counterexample": case,
                    "expected_assertion": reason,
                    "caught": caught,
                    "control_passed": intact,
                }
            )
    print(json.dumps(outcomes, indent=2))
    if not all(row["caught"] and row["control_passed"] for row in outcomes):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
