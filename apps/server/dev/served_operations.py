"""The Core API operations the deployed API routes: contracts/served-operations.json.

The contract says what Core may serve; this file says which of its operations a routed view
declares. A consumer that vendors the contract vendors this file from the same Core ref and fails
its own build on a call to an operation that is in the contract but not here: Core answers it 404,
or 405 on a path routed for other methods (run-notes/contract-gaps: 19 of 50 console calls were
unrouted, and nothing failed).

It is generated, never edited. The routes are the deployed API's: every path the urlconf that
config/settings/deploy.py names as ROOT_URLCONF reaches under `api/v1/`, each with the operations
its view declares through core.api.scopes.declares. tests/architecture/test_view_scopes.py walks
the same routes with this module's `routes` and holds each declaration to the contract's method,
path and scope; tests/test_served_operations.py fails when the checked-in file differs from what
the routes declare.

Not seen, as in test_view_scopes.py: the methods a plain function view's body answers, so a method
a function view declares and its body refuses (405) is listed; and a route a urlconf adds only
under settings other than the test settings, which the urlconfs do not do today.

    uv run python dev/served_operations.py           # rewrite the file
    uv run python dev/served_operations.py --check   # exit 1 and name each difference
"""

from __future__ import annotations

import ast
import json
import os
import re
import sys
from collections.abc import Callable, Iterable, Iterator, Mapping
from pathlib import Path
from typing import Any, NamedTuple

ROOT = Path(__file__).resolve().parents[1]
DEPLOY_SETTINGS = ROOT / "config" / "settings" / "deploy.py"
SERVED = ROOT / "contracts" / "served-operations.json"
API_PREFIX = "api/v1/"
NOTE = (
    "Generated by dev/served_operations.py from the deployed urlconf; do not edit. "
    "The operations of core-api.openapi.yaml a routed view declares."
)


class Route(NamedTuple):
    urlconf: str
    route: str
    callback: Callable[..., Any]


def _walk(urlconf: str, patterns: Iterable[Any], prefix: str) -> Iterator[Route | str]:
    from django.urls import URLPattern, URLResolver
    from django.urls.resolvers import LocalePrefixPattern, RegexPattern

    for pattern in patterns:
        if isinstance(pattern.pattern, RegexPattern | LocalePrefixPattern):
            yield (
                f"{urlconf}: {prefix}{pattern.pattern} is a regex route; "
                "routes are path() so their contract path can be read"
            )
        elif isinstance(pattern, URLResolver):
            yield from _walk(urlconf, pattern.url_patterns, f"{prefix}{pattern.pattern}")
        elif isinstance(pattern, URLPattern):
            yield Route(urlconf, f"{prefix}{pattern.pattern}", pattern.callback)


def routes(modules: Mapping[str, Iterable[Any]]) -> tuple[list[Route], list[str]]:
    """Every route the urlconfs reach, and a failure for each one this walk cannot read."""
    found: list[Route] = []
    unreadable: list[str] = []
    for urlconf, patterns in modules.items():
        for item in _walk(urlconf, patterns, ""):
            if isinstance(item, Route):
                found.append(item)
            else:
                unreadable.append(item)
    return found, unreadable


def owner(callback: Callable[..., Any]) -> Any:
    """The object a view's identity and declaration live on: its class, for a class view."""
    return getattr(callback, "view_class", None) or getattr(callback, "cls", None) or callback


def declared(callback: Callable[..., Any]) -> tuple[Any, ...] | None:
    """The operations a view declares, or None when it declares nothing."""
    from core.api.scopes import ATTRIBUTE

    for holder in (callback, owner(callback)):
        if hasattr(holder, ATTRIBUTE):
            return tuple(getattr(holder, ATTRIBUTE))
    return None


def contract_path(route: str) -> str | None:
    """The contract path of a route under `api/v1/`, or None for any other route."""
    if not route.startswith(API_PREFIX):
        return None
    return "/" + re.sub(r"<(?:\w+:)?(\w+)>", r"{\1}", route.removeprefix(API_PREFIX))


def deployed_urlconf(settings: Path = DEPLOY_SETTINGS) -> str:
    """The ROOT_URLCONF the API image serves, read without importing the deploy settings, which
    refuse to load outside a deployed environment."""
    found = [
        node.value.value
        for node in ast.walk(ast.parse(settings.read_text(encoding="utf-8")))
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "ROOT_URLCONF" for t in node.targets)
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    ]
    if len(found) != 1:
        raise SystemExit(f"{settings}: expected one string ROOT_URLCONF, found {len(found)}")
    return found[0]


def served(patterns: Iterable[Any]) -> list[dict[str, str]]:
    """One row per (operation, method, contract path) a routed view declares under api/v1/."""
    found, unreadable = routes({"served": patterns})
    if unreadable:
        raise ValueError("\n".join(unreadable))
    rows = set()
    for route in found:
        at = contract_path(route.route)
        if at is None:
            continue  # the agent API and the health probes are not Core API operations
        for operation in declared(route.callback) or ():
            rows.add((operation.operation_id, operation.method, at))
    return [
        {"operation_id": operation_id, "method": method, "path": at}
        for operation_id, method, at in sorted(rows)
    ]


def document(patterns: Iterable[Any]) -> str:
    body = {"note": NOTE, "operations": served(patterns)}
    return json.dumps(body, indent=2, ensure_ascii=False) + "\n"


def differences(expected: str, actual: str) -> list[str]:
    """What the checked-in file gets wrong, by operation; empty when it is current."""
    if expected == actual:
        return []
    try:
        have = json.loads(actual)
    except ValueError:
        return ["the file is not JSON: regenerate it"]

    def keyed(rows: object) -> set[tuple[str, str, str]]:
        if not isinstance(rows, list):
            return set()
        return {
            (str(r.get("operation_id")), str(r.get("method")), str(r.get("path")))
            for r in rows
            if isinstance(r, dict)
        }

    served_now = keyed(json.loads(expected)["operations"])
    listed = keyed(have.get("operations") if isinstance(have, dict) else None)
    found = [
        f"served but not listed: {operation_id} ({method} {at})"
        for operation_id, method, at in sorted(served_now - listed)
    ] + [
        f"listed but not served: {operation_id} ({method} {at})"
        for operation_id, method, at in sorted(listed - served_now)
    ]
    return found or ["the file differs from the generated one in form only: regenerate it"]


def main(argv: list[str]) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))  # run as a script, the repository root is not on the path
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings.test")
    import django
    from django.apps import apps

    if not apps.ready:
        # Set up once only: a second setup re-applies LOGGING, which binds the root handler to
        # whatever sys.stderr is at that moment (under pytest, a capture buffer it later closes).
        django.setup()
    from django.urls import get_resolver

    expected = document(get_resolver(deployed_urlconf()).url_patterns)
    if argv[1:] == ["--check"]:
        actual = SERVED.read_text(encoding="utf-8") if SERVED.exists() else ""
        found = differences(expected, actual) if actual else ["the file is missing"]
        for line in found:
            print(f"contracts/served-operations.json: {line}", file=sys.stderr)
        return 1 if found else 0
    if argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    SERVED.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
