// The extensions catalogue, generated from the extension manifests and from nothing else.
//
//   node extensions/catalog.mjs           write extensions/catalog.json and the README table
//   node extensions/catalog.mjs --check   refuse a catalogue that differs from the manifests,
//                                         an unlabelled extension, or a forbidden claim
//
// Every extension in this directory is a reference implementation: it runs against the SDK's
// in-memory harness with synthetic fixtures, and nothing in the repository installs it, hosts it
// or connects it to a provider account. The check keeps the catalogue and the wording honest.
import { lstat, readFile, readdir, realpath, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { validateManifest } from '../packages/extension-sdk/src/index.mjs'

// File-system paths throughout, joined with `path.join`. A name is never spliced into a URL:
// there `#` and `?` cut the path short and `%41` decodes to another name, so the check would
// read a different file from the one it lists, or none.
const ROOT = fileURLToPath(new URL('../', import.meta.url))
const SCANNED_DIRECTORIES = ['extensions', 'packages/extension-sdk']
const asPath = (root) => (root instanceof URL ? fileURLToPath(root) : String(root))
export const LABEL = 'Reference implementation'
export const CATALOG_PATH = 'extensions/catalog.json'
export const README_PATH = 'extensions/README.md'
export const TABLE_START = '<!-- catalogue:start (generated by extensions/catalog.mjs) -->'
export const TABLE_END = '<!-- catalogue:end -->'
const MANIFEST_NAMES = ['manifest.json', 'kodera-extension.json', 'extension.json']
const ID_PREFIX = 'io.kodera.ext.'
const SLUG = /^[a-z0-9][a-z0-9-]{1,62}$/u
// Hosts reserved for documentation (RFC 2606, RFC 6761): a manifest names no live endpoint.
const DOCUMENTATION_HOST = /(?:^|\.)example\.(?:org|com|net)$|\.(?:example|test|invalid)$/u
/**
 * What `collect` records for a path it did not read, with the reason. Only regular UTF-8 files
 * are read: a symbolic link is never followed, so nothing outside the repository is opened.
 */
export class NotRead {
  constructor(reason) {
    this.reason = reason
  }
}

// Wording that must not reappear. Each claim is a sequence of words, joined at run time, so
// that this file and its tests never contain the wording they refuse.
const words = (...parts) => new RegExp(`\\b${parts.join('[\\s-]+')}\\b`, 'iu')
const FORBIDDEN_CLAIMS = [
  ['an organisation named without its authorisation', new RegExp(`\\b(?:${['din', 'um'].join('')}|${['oc', 'to'].join('')})\\b`, 'iu')],
  ['a connector presented as live', words('live', '(?:connectors?|integrations?|connections?|feeds?|accounts?)')],
  ['a connector presented as live', words('(?:connecteurs?|comptes?)', '(?:en\\s+direct|connectés?|actifs?)')],
  ['an extension presented as official', words('official(?:ly)?', '(?:supported\\s+)?(?:kodera\\s+)?(?:[a-z-]+\\s+)?(?:extensions?|connectors?|integrations?)')],
  ['an extension presented as official', words('(?:connecteurs?|extensions?|intégrations?)', 'officiel(?:le)?s?')],
  ['an extension presented with an endorsement it does not have', words(`(?:${['cert', 'ified'].join('')}|production`, `ready|${['veri', 'fied'].join('')}\\s+partner)`)],
]

/** The manifest as the SDK validates it, whatever spelling the file uses. */
function normalise(raw, directory) {
  const id = typeof raw.id === 'string' ? raw.id : ''
  const slug = id.startsWith(ID_PREFIX) ? id.slice(ID_PREFIX.length) : id
  if (!SLUG.test(slug) || slug !== directory)
    throw new Error(`manifest id must be "${directory}" or "${ID_PREFIX}${directory}"`)
  const commands = (Array.isArray(raw.commands) ? raw.commands : []).map((command) => ({
    name: String(command?.name ?? command?.command ?? ''),
    description: String(command?.description ?? ''),
  }))
  return validateManifest({
    ...raw,
    schemaVersion: raw.schemaVersion ?? raw.schema,
    id: slug,
    scopes: Array.isArray(raw.scopes) ? raw.scopes : raw.permissions,
    commands,
  })
}

/** Extension directories and their one manifest, from a map of repository paths to text. */
function discover(files) {
  const directories = new Map()
  for (const path of files.keys()) {
    const match = /^extensions\/([^/]+)\/(.+)$/u.exec(path)
    if (!match) continue
    const found = directories.get(match[1]) ?? []
    if (MANIFEST_NAMES.includes(match[2])) found.push(match[2])
    directories.set(match[1], found)
  }
  return [...directories].sort(([a], [b]) => a.localeCompare(b))
}

/** The catalogue, and every reason it cannot be trusted. `files` maps repository paths to text. */
export function build(files) {
  const problems = []
  const extensions = []
  for (const [directory, manifests] of discover(files)) {
    const base = `extensions/${directory}`
    if (manifests.length !== 1) {
      problems.push(`${base}: exactly one manifest is the source (found ${manifests.length})`)
      continue
    }
    const manifestPath = `${base}/${manifests[0]}`
    let manifest
    try {
      manifest = normalise(JSON.parse(files.get(manifestPath)), directory)
    } catch (error) {
      problems.push(`${manifestPath}: ${error instanceof Error ? error.message : 'invalid manifest'}`)
      continue
    }
    if (!manifest.webhookUrl || !DOCUMENTATION_HOST.test(new URL(manifest.webhookUrl).hostname))
      problems.push(`${manifestPath}: webhookUrl must be a reserved documentation host, not a live endpoint`)
    const packagePath = `${base}/package.json`
    if (files.has(packagePath)) {
      const description = JSON.parse(files.get(packagePath)).description
      if (typeof description !== 'string' || !description.startsWith(`${LABEL}: `))
        problems.push(`${packagePath}: description must start with "${LABEL}: "`)
    }
    const readmePath = `${base}/README.md`
    if (files.has(readmePath) && !files.get(readmePath).includes(`Status: ${LABEL}`))
      problems.push(`${readmePath}: must carry "Status: ${LABEL}"`)
    extensions.push({
      slug: directory,
      id: `${ID_PREFIX}${directory}`,
      name: manifest.name,
      version: manifest.version,
      label: LABEL,
      description: manifest.description,
      manifest: manifestPath,
      readme: files.has(readmePath) ? readmePath : null,
      scopes: [...manifest.scopes],
      events: [...manifest.events],
      commands: manifest.commands.map((command) => ({
        name: command.name.startsWith('/') ? command.name : `/${command.name}`,
        description: command.description,
      })),
      webhookUrl: manifest.webhookUrl ?? null,
    })
  }
  const catalog = {
    schemaVersion: 'kodera.extensions.catalog.v1',
    generatedBy: 'extensions/catalog.mjs',
    label: LABEL,
    notice:
      'Generated from the extension manifests. Every entry is a reference implementation exercised with synthetic fixtures: it is not installed, hosted or connected to a provider account by this repository.',
    extensions,
  }
  return { catalog, problems }
}

export const serialise = (catalog) => `${JSON.stringify(catalog, null, 2)}\n`

const cell = (text) => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ')

/** The README table, between its two markers. */
export function table(catalog) {
  const rows = catalog.extensions.map(
    (entry) =>
      `| [\`${entry.slug}\`](./${entry.slug}) | ${cell(entry.name)} | *${entry.label}* | ${
        entry.commands.map((command) => `\`${cell(command.name)}\``).join(', ') || 'none'
      } | [\`${entry.manifest.split('/').at(-1)}\`](./${entry.manifest.slice('extensions/'.length)}) |`,
  )
  return [
    TABLE_START,
    '| Directory | Name | Status | Slash commands | Manifest |',
    '| :--- | :--- | :--- | :--- | :--- |',
    ...rows,
    TABLE_END,
  ].join('\n')
}

/** The README with its table replaced, or null when the markers are missing. */
export function withTable(readme, catalog) {
  const start = readme.indexOf(TABLE_START)
  const end = readme.indexOf(TABLE_END)
  if (start < 0 || end < start) return null
  return readme.slice(0, start) + table(catalog) + readme.slice(end + TABLE_END.length)
}

/** Every refusal, by name: drift between manifests and catalogue, labels, and forbidden claims. */
export function problemsIn(tree) {
  // A path that was not read is refused by name, and nothing else is said about it.
  const unread = [...tree].filter(([, text]) => text instanceof NotRead).sort(([a], [b]) => a.localeCompare(b))
  const files = new Map([...tree].filter(([, text]) => typeof text === 'string'))
  const { catalog, problems } = build(files)
  for (const [path, entry] of unread)
    problems.unshift(`${path}: ${entry.reason} refused: the check reads regular UTF-8 files inside the repository only`)
  if (files.get(CATALOG_PATH) !== serialise(catalog))
    problems.push(`${CATALOG_PATH} drifted from the extension manifests`)
  const readme = files.get(README_PATH)
  if (readme === undefined || withTable(readme, catalog) !== readme)
    problems.push(`${README_PATH} catalogue table drifted from the extension manifests`)
  if (readme !== undefined && !readme.includes(`Status: ${LABEL}s`))
    problems.push(`${README_PATH}: must carry "Status: ${LABEL}s"`)
  for (const [path, text] of [...files].sort(([a], [b]) => a.localeCompare(b)))
    for (const [claim, pattern] of FORBIDDEN_CLAIMS)
      if (pattern.test(text)) problems.push(`forbidden claim in ${path}: ${claim}`)
  return [...new Set(problems)]
}

/**
 * Every file of `extensions/` and `packages/extension-sdk/`, by repository path: its text, or a
 * `NotRead` with the reason. Nothing is skipped for its name or its type.
 *
 * A file is read only when its real path is the root's real path joined with its own: no
 * symbolic link is followed, in the file's name or in any directory above it, the two scanned
 * directories and their parents included. Each entry is read from exactly the path it is
 * listed under, whatever characters its name holds.
 */
export async function collect(root = ROOT) {
  const base = asPath(root)
  const realBase = await realpath(base)
  const files = new Map()
  const decoder = new TextDecoder('utf-8', { fatal: true })
  const local = (path) => join(base, ...path.split('/'))
  const contained = async (path) => (await realpath(local(path))) === join(realBase, ...path.split('/'))
  async function walk(directory) {
    for (const entry of await readdir(local(directory), { withFileTypes: true })) {
      if (entry.name === 'node_modules' && entry.isDirectory()) continue
      const path = `${directory}/${entry.name}`
      // A name that cannot be printed on one line cannot be named in a refusal either.
      if (/[\p{Cc}\\]/u.test(entry.name)) files.set(JSON.stringify(path), new NotRead('entry with an unprintable name'))
      else if (entry.isSymbolicLink()) files.set(path, new NotRead('symbolic link'))
      else if (entry.isDirectory()) await walk(path)
      else if (!entry.isFile()) files.set(path, new NotRead('special file'))
      else if (!(await contained(path))) files.set(path, new NotRead('file reached through a symbolic link'))
      else {
        try {
          files.set(path, decoder.decode(await readFile(local(path))))
        } catch (error) {
          if (!(error instanceof TypeError)) throw error
          files.set(path, new NotRead('file that is not UTF-8 text'))
        }
      }
    }
  }
  for (const directory of SCANNED_DIRECTORIES) {
    let entry
    try {
      entry = await lstat(local(directory))
    } catch (error) {
      if (error?.code !== 'ENOENT' && error?.code !== 'ENOTDIR') throw error
      files.set(directory, new NotRead('missing directory'))
      continue
    }
    if (entry.isSymbolicLink()) files.set(directory, new NotRead('symbolic link'))
    else if (!entry.isDirectory()) files.set(directory, new NotRead('entry that is not a directory'))
    else if (!(await contained(directory))) files.set(directory, new NotRead('directory reached through a symbolic link'))
    else await walk(directory)
  }
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tree = await collect()
  const files = new Map([...tree].filter(([, text]) => typeof text === 'string'))
  if (process.argv.includes('--check')) {
    const problems = problemsIn(tree)
    for (const problem of problems) console.error(`[FAIL] ${problem}`)
    if (problems.length) process.exit(1)
    console.log(`OK: extensions catalogue matches ${build(files).catalog.extensions.length} manifests; no forbidden claim`)
  } else {
    const { catalog } = build(files)
    // Nothing is written through a link, and nothing is generated from a tree that was not fully read.
    const unread = [...tree].filter(([, text]) => text instanceof NotRead).map(([path]) => path)
    if (unread.length) throw new Error(`refusing to generate: not read: ${unread.join(', ')}`)
    const readme = withTable(files.get(README_PATH) ?? '', catalog)
    if (readme === null) throw new Error(`${README_PATH} has no catalogue markers`)
    for (const [path, text] of [[CATALOG_PATH, serialise(catalog)], [README_PATH, readme]]) {
      const target = join(ROOT, ...path.split('/'))
      const entry = await lstat(target).catch(() => null)
      if (entry !== null && !entry.isFile()) throw new Error(`refusing to write ${path}: not a regular file`)
      await writeFile(target, text)
    }
    console.log(`Wrote ${CATALOG_PATH} and the ${README_PATH} table from ${catalog.extensions.length} manifests`)
  }
}
