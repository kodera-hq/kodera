#!/usr/bin/env python3
"""Bind generated native clients to current tokens and an in-repository producer."""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def check(pin, source, committed_source, generated, consumer, manifest):
    assert re.fullmatch(r"[0-9a-f]{40}", pin["producerCommit"]), "invalid producer commit"
    assert pin["producerRepository"] == "kodera-hq/kodera", "wrong producer repository"
    assert source == committed_source, "producer commit does not hold the current source"
    assert pin["sourceSha256"] == sha(source), "source checksum drift"
    assert consumer == generated, "generated consumer drift"
    assert pin["generatedSha256"] == sha(generated), "generated checksum drift"
    assert pin["manifestSha256"] == sha(manifest), "manifest checksum drift"
    assert json.loads(manifest)["source"]["sha256"] == sha(source), "manifest source drift"


def main():
    source = (ROOT / "packages/design-tokens/tokens.json").read_bytes()
    manifest = (ROOT / "packages/design-tokens/dist/native/manifest.json").read_bytes()
    clients = [
        ("apps/ios/App/Generated/TokenProvenance.json", "swift", "apps/ios/App/Generated/KoderaTokens.swift"),
        ("apps/android/app/src/main/assets/provenance/tokens.json", "kt", "apps/android/app/src/main/kotlin/io/kodera/tokens/KoderaTokens.kt"),
    ]
    for pin_path, extension, consumer_path in clients:
        pin = json.loads((ROOT / pin_path).read_bytes())
        commit = pin["producerCommit"]
        assert re.fullmatch(r"[0-9a-f]{40}", commit), "invalid producer commit"
        committed = subprocess.check_output(["git", "-C", str(ROOT), "show", f"{commit}:packages/design-tokens/tokens.json"])
        generated = (ROOT / f"packages/design-tokens/dist/native/KoderaTokens.{extension}").read_bytes()
        consumer = (ROOT / consumer_path).read_bytes()
        check(pin, source, committed, generated, consumer, manifest)
        if "--selftest" in sys.argv:
            for index, message in [(1, "source"), (2, "producer"), (3, "generated"), (4, "consumer"), (5, "manifest")]:
                arguments = [pin, source, committed, generated, consumer, manifest]
                arguments[index] += b" "
                try:
                    check(*arguments)
                except AssertionError:
                    pass
                else:
                    raise AssertionError(f"missed {message} mutation")
    print("PASS: native generated bytes, source checksums and producer commits agree")


if __name__ == "__main__":
    main()
