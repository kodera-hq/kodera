#!/usr/bin/env python3
"""Check the repository's top-level documentation: links, the ADR index and retired wording.

Three refusals, each by name:

  1. A relative link or an anchor that leads nowhere, in the documents listed in SOURCES and
     in the ADRs the index points to. External URLs are not fetched: this check is offline
     and has no dependency.
  2. An ADR that `docs/adr/README.md` does not index, an indexed ADR that does not exist,
     an identifier that does not match the file it points to, or a title that drifted.
  3. Wording the project retired: an organisation named without its authorisation, the
     former name of the `#proximity` channel outside its naming note, and a connector or
     extension presented as official or live.

    python3 scripts/ci/check-docs-truth.py              check
    python3 scripts/ci/check-docs-truth.py --selftest   prove every refusal can fail
    python3 scripts/ci/check-docs-truth.py --write-adr-index   regenerate the ADR table
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[2]

# Documents whose links are checked, as repository-relative paths or directories.
SOURCES = (
    "README.md",
    "ARCHITECTURE.md",
    "ROADMAP.md",
    "AGENTS.md",
    "docs",
    "ee/billing/README.md",
    "deploy/community",
    "packages/create-kodera",
    "packages/extension-sdk",
    "extensions",
)
# Text files whose wording is checked: the documents above and what ships beside them.
WORDING_SUFFIXES = (".md", ".json", ".py", ".mjs", ".ts", ".yml", ".yaml", ".example", ".sh")
WORDING_FILES = ("Caddyfile",)
WORDING_EXEMPT = ("LICENSE",)

ADR_INDEX = "docs/adr/README.md"
ADR_TABLE_START = "<!-- adr-index:start (generated by scripts/ci/check-docs-truth.py --write-adr-index) -->"
ADR_TABLE_END = "<!-- adr-index:end -->"
# Where ADRs live, and the stable prefix of their identifiers. An ADR is never moved or copied
# here: the index links to it in place.
ADR_SOURCES = (
    ("SRV", "Server control plane", "apps/server/docs/adr"),
    ("WEB", "Web client", "apps/web/docs/adr"),
    ("TOK", "Design tokens", "packages/design-tokens/docs/adr"),
)
# The index's targets are link-checked too: a record the index sends a reader to must not lead
# that reader to a dead end. Their wording is their package's own business.
LINK_SOURCES = SOURCES + tuple(directory for _prefix, _label, directory in ADR_SOURCES)
ADR_FILE_RE = re.compile(r"(\d{4})-[a-z0-9][a-z0-9-]*\.md")
ADR_ROW_RE = re.compile(r"\| `([A-Z]+-ADR-\d{4})` \| \[(.+)\]\(([^)\s]+)\) \|")


def _phrase(*parts: str) -> re.Pattern[str]:
    return re.compile(r"\b" + r"[\s-]+".join(parts) + r"\b", re.IGNORECASE)


# Each pattern is assembled from fragments so that this file never contains what it refuses.
RETIRED_WORDING: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("an organisation named without its authorisation",
     re.compile(r"\b(?:" + "din" + "um" + "|" + "oc" + r"to)\b", re.IGNORECASE)),
    ("a connector presented as live",
     _phrase("live", r"(?:connectors?|integrations?|connections?|feeds?|accounts?)")),
    ("a connector presented as live",
     _phrase(r"(?:connecteurs?|comptes?)", r"(?:en\s+direct|connectés?|actifs?)")),
    ("an extension presented as official",
     _phrase(r"official(?:ly)?", r"(?:supported\s+)?(?:kodera\s+)?(?:[a-z-]+\s+)?(?:extensions?|connectors?|integrations?)")),
    ("an extension presented as official",
     _phrase(r"(?:connecteurs?|extensions?|intégrations?)", r"officiel(?:le)?s?")),
)
FORMER_CHANNEL_NAME = re.compile("ur" + "gence", re.IGNORECASE)
# The one place the former name may appear: a sentence that says it is the former name.
NAMING_NOTE = re.compile(r"first called|formerly|former name|was first named", re.IGNORECASE)

FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})")
INLINE_CODE_RE = re.compile(r"(`+)(.+?)\1")
INLINE_LINK_RE = re.compile(r"!?\[(?:[^\]\[]|\[[^\]]*\])*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
REFERENCE_DEF_RE = re.compile(r"^\s{0,3}\[[^\]]+\]:\s*<?(\S+?)>?(?:\s+\"[^\"]*\")?\s*$")
HTML_LINK_RE = re.compile(r"""\b(?:href|src|srcset)\s*=\s*["']([^"']+)["']""", re.IGNORECASE)
HTML_ANCHOR_RE = re.compile(r"""<a\s[^>]*\b(?:id|name)\s*=\s*["']([^"']+)["']""", re.IGNORECASE)
HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s+(.+?)\s*#*\s*$")
SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]*:")


def tracked_files(root: Path) -> set[str]:
    """Paths the repository publishes, and files not yet added that it does not ignore. Outside
    a git checkout (the self-test's fixture), every file on disk counts."""
    listing = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        capture_output=True, check=False,
    )
    if listing.returncode == 0 and listing.stdout:
        return {path for path in listing.stdout.decode("utf-8").split("\0") if path and (root / path).is_file()}
    return {
        path.relative_to(root).as_posix()
        for path in root.rglob("*")
        if path.is_file() and ".git" not in path.relative_to(root).parts
    }


def selected(files: set[str], sources: tuple[str, ...]) -> list[str]:
    return sorted(
        path for path in files
        if any(path == source or path.startswith(source.rstrip("/") + "/") for source in sources)
    )


def prose_lines(text: str) -> list[tuple[int, str]]:
    """Lines outside fenced code blocks, with inline code removed: code is not a link."""
    lines: list[tuple[int, str]] = []
    fence: str | None = None
    for number, line in enumerate(text.splitlines(), start=1):
        opened = FENCE_RE.match(line)
        if fence is None and opened:
            fence = opened.group(2)[0] * 3
            continue
        if fence is not None:
            if line.strip().startswith(fence):
                fence = None
            continue
        lines.append((number, INLINE_CODE_RE.sub("", line)))
    return lines


def heading_anchor(title: str) -> str:
    """The anchor GitHub gives a heading: lower case, punctuation dropped, spaces to hyphens."""
    title = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", title)
    title = re.sub(r"<[^>]+>", "", title).replace("`", "")
    kept = [
        char for char in title.strip().lower()
        if char in "-_ " or unicodedata.category(char)[0] in ("L", "N", "M")
    ]
    return "".join(kept).replace(" ", "-")


def anchors_of(text: str) -> set[str]:
    anchors: set[str] = set()
    seen: dict[str, int] = {}
    fence: str | None = None
    for line in text.splitlines():
        opened = FENCE_RE.match(line)
        if fence is None and opened:
            fence = opened.group(2)[0] * 3
            continue
        if fence is not None:
            if line.strip().startswith(fence):
                fence = None
            continue
        anchors.update(HTML_ANCHOR_RE.findall(line))
        heading = HEADING_RE.match(line)
        if heading:
            base = heading_anchor(heading.group(2))
            count = seen.get(base, 0)
            seen[base] = count + 1
            anchors.add(base if count == 0 else f"{base}-{count}")
    return anchors


def link_targets(text: str) -> list[tuple[int, str]]:
    targets: list[tuple[int, str]] = []
    for number, line in prose_lines(text):
        found = INLINE_LINK_RE.findall(line) + HTML_LINK_RE.findall(line)
        definition = REFERENCE_DEF_RE.match(line)
        if definition:
            found.append(definition.group(1))
        for target in found:
            # A srcset holds several candidates, each a URL and an optional descriptor.
            for candidate in target.split(","):
                candidate = candidate.strip().split(" ")[0]
                if candidate:
                    targets.append((number, candidate))
    return targets


def resolve(source: str, target: str) -> str | None:
    """The repository path a relative link names, or None when it leaves the repository."""
    base = PurePosixPath(source).parent
    parts: list[str] = []
    for part in (PurePosixPath("/") / target.lstrip("/") if target.startswith("/") else base / target).parts:
        if part in ("", ".", "/"):
            continue
        if part == "..":
            if not parts:
                return None
            parts.pop()
        else:
            parts.append(part)
    return "/".join(parts)


def check_links(root: Path, files: set[str], sources: tuple[str, ...] = LINK_SOURCES) -> list[str]:
    errors: list[str] = []
    directories = {str(parent) for path in files for parent in PurePosixPath(path).parents}
    anchor_cache: dict[str, set[str]] = {}

    def anchors(path: str) -> set[str]:
        if path not in anchor_cache:
            anchor_cache[path] = anchors_of((root / path).read_text(encoding="utf-8"))
        return anchor_cache[path]

    for source in selected(files, sources):
        if not source.endswith(".md"):
            continue
        for number, target in link_targets((root / source).read_text(encoding="utf-8")):
            if SCHEME_RE.match(target) or target.startswith("//"):
                continue
            path_part, _, fragment = target.partition("#")
            path_part = path_part.split("?", 1)[0]
            where = f"{source}:{number}"
            if not path_part:
                destination: str | None = source
            else:
                destination = resolve(source, path_part)
                if destination is None:
                    errors.append(f"{where}: broken link '{target}': it leaves the repository")
                    continue
                if destination not in files and destination not in directories and destination != "":
                    errors.append(f"{where}: broken link '{target}': no tracked file or directory '{destination}'")
                    continue
            if fragment and destination in files and destination.endswith(".md"):
                if fragment.lower() not in anchors(destination):
                    errors.append(f"{where}: broken anchor '{target}': no heading '#{fragment}' in {destination}")
    return errors


def adr_title(text: str) -> str | None:
    for line in text.splitlines():
        heading = re.match(r"#\s+(.+?)\s*$", line)
        if heading:
            return heading.group(1)
    return None


def adr_inventory(root: Path, files: set[str]) -> tuple[dict[str, tuple[str, str]], list[str]]:
    """Every ADR on disk as identifier -> (path, title)."""
    found: dict[str, tuple[str, str]] = {}
    errors: list[str] = []
    for prefix, _label, directory in ADR_SOURCES:
        for path in sorted(files):
            parent, _, name = path.rpartition("/")
            match = ADR_FILE_RE.fullmatch(name) if parent == directory else None
            if not match or match.group(1) == "0000":
                continue
            identifier = f"{prefix}-ADR-{match.group(1)}"
            title = adr_title((root / path).read_text(encoding="utf-8"))
            if title is None:
                errors.append(f"ADR has no title: {path}")
            elif identifier in found:
                errors.append(f"two ADRs share the identifier {identifier}: {found[identifier][0]} and {path}")
            else:
                found[identifier] = (path, title)
    return found, errors


def adr_table(inventory: dict[str, tuple[str, str]]) -> str:
    lines = [ADR_TABLE_START]
    index_parent = PurePosixPath(ADR_INDEX).parent
    for prefix, label, directory in ADR_SOURCES:
        rows = sorted(item for item in inventory.items() if item[0].startswith(prefix + "-"))
        lines += ["", f"### {label} (`{prefix}-ADR-*`, in `{directory}/`)", "", "| Identifier | Decision |", "| :--- | :--- |"]
        for identifier, (path, title) in rows:
            up = "../" * len(index_parent.parts)
            lines.append(f"| `{identifier}` | [{title.replace('|', chr(92) + '|')}]({up}{path}) |")
    lines += ["", ADR_TABLE_END]
    return "\n".join(lines)


def check_adr_index(root: Path, files: set[str]) -> list[str]:
    inventory, errors = adr_inventory(root, files)
    if ADR_INDEX not in files:
        return errors + [f"ADR index is missing: {ADR_INDEX}"]
    text = (root / ADR_INDEX).read_text(encoding="utf-8")
    rows: dict[str, tuple[str, str | None]] = {}
    for identifier, title, target in ADR_ROW_RE.findall(text):
        if identifier in rows:
            errors.append(f"ADR indexed twice: {identifier}")
        rows[identifier] = (title.replace("\\|", "|"), resolve(ADR_INDEX, target.partition("#")[0]))
    for identifier, (path, title) in sorted(inventory.items()):
        if identifier not in rows:
            errors.append(f"ADR not indexed: {path} (expected {identifier} in {ADR_INDEX})")
            continue
        indexed_title, indexed_path = rows[identifier]
        if indexed_path != path:
            errors.append(f"ADR index points {identifier} at '{indexed_path}', not at {path}")
        elif indexed_title != title:
            errors.append(f"ADR index title drifted for {identifier}: run --write-adr-index")
    for identifier, (_title, indexed_path) in sorted(rows.items()):
        if identifier not in inventory:
            errors.append(f"indexed ADR does not exist: {identifier} -> {indexed_path}")
    return errors


def write_adr_index(root: Path, files: set[str]) -> None:
    inventory, errors = adr_inventory(root, files)
    if errors:
        sys.exit("\n".join(errors))
    index = root / ADR_INDEX
    text = index.read_text(encoding="utf-8")
    start, end = text.find(ADR_TABLE_START), text.find(ADR_TABLE_END)
    if start < 0 or end < start:
        sys.exit(f"{ADR_INDEX} has no index markers")
    index.write_text(text[:start] + adr_table(inventory) + text[end + len(ADR_TABLE_END):], encoding="utf-8")
    print(f"Wrote {len(inventory)} ADRs to {ADR_INDEX}")


def check_wording(root: Path, files: set[str], sources: tuple[str, ...] = SOURCES) -> list[str]:
    errors: list[str] = []
    for path in selected(files, sources):
        name = PurePosixPath(path).name
        if name in WORDING_EXEMPT or not (name.endswith(WORDING_SUFFIXES) or name in WORDING_FILES):
            continue
        try:
            text = (root / path).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            for claim, pattern in RETIRED_WORDING:
                if pattern.search(line):
                    errors.append(f"{path}:{number}: retired wording: {claim}")
            if FORMER_CHANNEL_NAME.search(line) and not NAMING_NOTE.search(line):
                errors.append(
                    f"{path}:{number}: retired wording: the channel is `proximity` "
                    "(the former name may appear only in a sentence that says it is the former name)"
                )
    return errors


def check(root: Path) -> list[str]:
    files = tracked_files(root)
    return check_links(root, files) + check_adr_index(root, files) + check_wording(root, files)


def selftest() -> None:
    """Build a small repository, check it passes, then break it one way at a time."""
    base = {
        "README.md": (
            "# Project\n\nSee [the guide](./docs/guide.md#getting-started), [the index](docs/adr/README.md)\n"
            "and [deploy](./deploy/community/).\n\n<a href=\"./docs/guide.md\"><img src=\"./logo.svg\"></a>\n\n"
            "```\n[not a link](./nowhere.md)\n```\n`[nor this](./nowhere.md)`\n"
        ),
        "logo.svg": "<svg/>\n",
        "ARCHITECTURE.md": "# Architecture\n\n[up](#architecture) and [ref]\n\n[ref]: ./README.md\n",
        "docs/guide.md": "# Guide\n\n## Getting started\n\n## Getting started\n\n[again](#getting-started-1) [home](../README.md)\n",
        "deploy/community/README.md": "# Deploy\n\nThis channel was first called `#ur" + "gence`. Now `#proximity`.\n",
        "apps/server/docs/adr/0000-template.md": "# ADR-0000: Template\n",
        "apps/server/docs/adr/0001-first.md": "# ADR-0001: First | decision\n",
        "apps/web/docs/adr/0001-console.md": "# ADR-0001: Console\n",
        "packages/design-tokens/docs/adr/0001-tokens.md": "# ADR-0001: Tokens\n",
        ADR_INDEX: f"# Decisions\n\n{ADR_TABLE_START}\n{ADR_TABLE_END}\n",
    }
    organisation = "DIN" + "UM"

    def run(changes: dict[str, str | None], regenerate: bool = False) -> list[str]:
        with tempfile.TemporaryDirectory(prefix="docs-truth-selftest-") as tmp:
            root = Path(tmp)
            for path, text in {**base, **changes}.items():
                if text is None:
                    continue
                (root / path).parent.mkdir(parents=True, exist_ok=True)
                (root / path).write_text(text, encoding="utf-8")
            if regenerate:
                write_index_quietly(root)
            return check(root)

    def write_index_quietly(root: Path) -> None:
        files = tracked_files(root)
        inventory, _ = adr_inventory(root, files)
        index = root / ADR_INDEX
        text = index.read_text(encoding="utf-8")
        start, end = text.find(ADR_TABLE_START), text.find(ADR_TABLE_END)
        index.write_text(text[:start] + adr_table(inventory) + text[end + len(ADR_TABLE_END):], encoding="utf-8")

    with tempfile.TemporaryDirectory(prefix="docs-truth-selftest-") as tmp:
        root = Path(tmp)
        for path, text in base.items():
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_text(text, encoding="utf-8")
        write_index_quietly(root)
        indexed = (root / ADR_INDEX).read_text(encoding="utf-8")
    base[ADR_INDEX] = indexed

    failures: list[str] = []
    baseline = run({})
    if baseline:
        sys.exit("check-docs-truth selftest: the valid fixture must pass first: " + "; ".join(baseline))

    cases: list[tuple[str, dict[str, str | None], str]] = [
        ("a link to a file that does not exist",
         {"README.md": base["README.md"] + "\n[gone](./docs/missing.md)\n"},
         "README.md:13: broken link './docs/missing.md': no tracked file or directory 'docs/missing.md'"),
        ("a link whose target was deleted",
         {"docs/guide.md": None, "ARCHITECTURE.md": base["ARCHITECTURE.md"]},
         "README.md:3: broken link './docs/guide.md#getting-started': no tracked file or directory 'docs/guide.md'"),
        ("an anchor that no heading carries",
         {"README.md": base["README.md"].replace("#getting-started", "#installing")},
         "README.md:3: broken anchor './docs/guide.md#installing': no heading '#installing' in docs/guide.md"),
        ("an in-page anchor that no heading carries",
         {"ARCHITECTURE.md": base["ARCHITECTURE.md"].replace("(#architecture)", "(#design)")},
         "ARCHITECTURE.md:3: broken anchor '#design': no heading '#design' in ARCHITECTURE.md"),
        ("a reference definition that leads nowhere",
         {"ARCHITECTURE.md": base["ARCHITECTURE.md"].replace("[ref]: ./README.md", "[ref]: ./READ.md")},
         "ARCHITECTURE.md:5: broken link './READ.md': no tracked file or directory 'READ.md'"),
        ("an HTML image that does not exist",
         {"logo.svg": None},
         "README.md:6: broken link './logo.svg': no tracked file or directory 'logo.svg'"),
        ("a link that leaves the repository",
         {"docs/guide.md": base["docs/guide.md"].replace("(../README.md)", "(../../outside.md)")},
         "docs/guide.md:7: broken link '../../outside.md': it leaves the repository"),
        ("a new ADR that the index does not list",
         {"packages/design-tokens/docs/adr/0002-second.md": "# ADR-0002: Second\n"},
         f"ADR not indexed: packages/design-tokens/docs/adr/0002-second.md (expected TOK-ADR-0002 in {ADR_INDEX})"),
        ("an indexed ADR that was deleted",
         {"apps/web/docs/adr/0001-console.md": None},
         "indexed ADR does not exist: WEB-ADR-0001 -> apps/web/docs/adr/0001-console.md"),
        ("an indexed ADR that was renamed",
         {"apps/web/docs/adr/0001-console.md": None, "apps/web/docs/adr/0001-console-app.md": "# ADR-0001: Console\n"},
         "ADR index points WEB-ADR-0001 at 'apps/web/docs/adr/0001-console.md', not at apps/web/docs/adr/0001-console-app.md"),
        ("an identifier that names another ADR",
         {ADR_INDEX: indexed.replace("`WEB-ADR-0001`", "`WEB-ADR-0009`")},
         "indexed ADR does not exist: WEB-ADR-0009 -> apps/web/docs/adr/0001-console.md"),
        ("an ADR title that changed after indexing",
         {"apps/server/docs/adr/0001-first.md": "# ADR-0001: First decision, revised\n"},
         "ADR index title drifted for SRV-ADR-0001: run --write-adr-index"),
        ("a dead link inside an indexed ADR",
         {"apps/web/docs/adr/0001-console.md": "# ADR-0001: Console\n\nSee [the spec](../specs/console.md).\n"},
         "apps/web/docs/adr/0001-console.md:3: broken link '../specs/console.md': no tracked file or directory 'apps/web/docs/specs/console.md'"),
        ("the index itself is deleted",
         {ADR_INDEX: None, "README.md": base["README.md"].replace(", [the index](docs/adr/README.md)", "")},
         f"ADR index is missing: {ADR_INDEX}"),
        ("an organisation named without its authorisation",
         {"docs/guide.md": base["docs/guide.md"] + f"\nDesign partner: {organisation}.\n"},
         "docs/guide.md:9: retired wording: an organisation named without its authorisation"),
        ("the former channel name outside its naming note",
         {"deploy/community/workspace-templates.json": '{"channels": ["ur' + 'gence"]}\n'},
         "deploy/community/workspace-templates.json:1: retired wording: the channel is `proximity`"),
        ("a connector presented as live",
         {"extensions/README.md": "# Extensions\n\nA " + "live" + " connector to the bank.\n"},
         "extensions/README.md:3: retired wording: a connector presented as live"),
        ("an extension presented as official",
         {"extensions/README.md": "# Extensions\n\nThe " + "official" + " Kodera extension.\n"},
         "extensions/README.md:3: retired wording: an extension presented as official"),
    ]
    for label, changes, expected in cases:
        got = run(changes)
        if not any(error.startswith(expected) for error in got):
            failures.append(f"'{label}' did not report '{expected}' (got {got})")
    accepted = run({"packages/design-tokens/docs/adr/0002-second.md": "# ADR-0002: Second\n"}, regenerate=True)
    if accepted:
        failures.append(f"a regenerated index must accept a new ADR (got {accepted})")
    if failures:
        sys.exit("check-docs-truth selftest FAILED:\n  " + "\n  ".join(failures))
    print(f"OK: check-docs-truth selftest, {len(cases)} refusals named and 2 accepted cases")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--write-adr-index", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        selftest()
        return
    root = args.root.resolve()
    if args.write_adr_index:
        write_adr_index(root, tracked_files(root))
        return
    errors = check(root)
    if errors:
        for error in errors:
            print(f"[FAIL] {error}", file=sys.stderr)
        sys.exit(1)
    files = tracked_files(root)
    documents = sum(1 for path in selected(files, LINK_SOURCES) if path.endswith(".md"))
    print(f"OK: {documents} documents, {len(adr_inventory(root, files)[0])} indexed ADRs, no retired wording")


if __name__ == "__main__":
    main()
