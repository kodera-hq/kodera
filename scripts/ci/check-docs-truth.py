def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--write-adr-index", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        selftest()
        return
    try:
        tree = survey(args.root)
        if args.write_adr_index:
            write_adr_index(tree)
            return
        errors = check_readable(tree) + check_links(tree) + check_adr_index(tree) + check_wording(tree)
    except CouldNotLook as error:
        sys.exit(f"[FAIL] could not look: {error}")
    if errors:
        for error in errors:
            print(f"[FAIL] {error}", file=sys.stderr)
        sys.exit(1)
    documents = sum(1 for path in selected(tree.files, LINK_SOURCES) if path.endswith(".md"))
    print(f"OK: {documents} documents, {len(adr_inventory(tree)[0])} indexed ADRs, no retired wording")


